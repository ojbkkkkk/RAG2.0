#!/bin/bash
# 矩阵-知识库管理系统 - 一键重启脚本

set -uo pipefail

# ── 颜色定义 ──────────────────────────────────────────────────
GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

# ── 项目路径 ──────────────────────────────────────────────────
PROJECT_DIR="$(cd "$(dirname "$0")" && pwd)"

echo ""
echo -e "${BLUE}正在重启 矩阵-知识库管理系统...${NC}"
echo ""

# ── 停止服务 ──────────────────────────────────────────────────
"$PROJECT_DIR/stop.sh"
if [[ $? -ne 0 ]]; then
    echo -e "停止服务时出现问题，继续尝试启动..."
fi

# 等待端口释放
sleep 2

# ── 启动服务 ──────────────────────────────────────────────────
"$PROJECT_DIR/start.sh"
